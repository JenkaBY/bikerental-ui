import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { CONTAINER_APPS, DEFAULT_LOCALE_SEGMENT, ROOT_APP } from './apps.mjs';

const STAGING = 'staging';
const DOCKERFILE = join('docker', 'Dockerfile');
const OUTPUT = join('docker', 'Caddyfile.generated');
const LISTEN_PORT = 8080;
const APP_SEGMENT_PATTERN = /^[a-z][a-z0-9-]*$/;
const LOCALE_SEGMENT_PATTERN = /^[A-Za-z]{2}(-[A-Za-z0-9]+)?$/;

function localeSegmentsOf(app) {
  const appDir = join(STAGING, app);

  if (!existsSync(appDir)) {
    throw new Error(
      `No ${appDir}/ — '${app}' is listed in CONTAINER_APPS but was not assembled into staging.`,
    );
  }

  const segments = readdirSync(appDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  for (const segment of segments) {
    if (!LOCALE_SEGMENT_PATTERN.test(segment)) {
      throw new Error(
        `${appDir}/${segment} is not a valid locale segment (expected e.g. 'en' or 'pt-BR'). ` +
          'Locale segments are written verbatim into a routing regex, so they must carry no metacharacters.',
      );
    }

    if (!existsSync(join(appDir, segment, 'index.html'))) {
      throw new Error(`${appDir}/${segment}/index.html is missing — that locale would serve nothing.`);
    }
  }

  if (segments.length === 0) {
    throw new Error(`${appDir}/ holds no locale directories.`);
  }

  if (!segments.includes(DEFAULT_LOCALE_SEGMENT)) {
    throw new Error(
      `${appDir}/${DEFAULT_LOCALE_SEGMENT}/ is missing. Every request for an unbuilt locale falls back ` +
        `to '${DEFAULT_LOCALE_SEGMENT}', so it is the one locale that must always exist.`,
    );
  }

  return segments;
}

function assertEveryAppIsCopiedIntoTheImage() {
  const dockerfile = readFileSync(DOCKERFILE, 'utf-8');
  const missing = ALL_APPS.filter(
    (app) => !dockerfile.includes(`COPY ${STAGING}/${app} /srv/${app}`),
  );

  if (missing.length > 0) {
    throw new Error(
      `${DOCKERFILE} has no COPY line for [${missing}]. Each application is copied as its own layer, ` +
        'so a missing line ships an image that routes to files it does not contain.',
    );
  }
}

// Both kinds of application, in one list, wherever the distinction does not matter — which is every
// check that asks "did this get built and copied?" The distinction is only about URL shape.
const ALL_APPS = [ROOT_APP, ...CONTAINER_APPS];

function resolveLocaleSegments() {
  const perApp = ALL_APPS.map((app) => [app, localeSegmentsOf(app)]);
  const [firstApp, expected] = perApp[0];

  for (const [app, segments] of perApp.slice(1)) {
    if (segments.join(',') !== expected.join(',')) {
      throw new Error(
        `Locale sets differ: '${firstApp}' ships [${expected}] but '${app}' ships [${segments}]. ` +
          'One alternation serves every application, so the sets must match. Give every application the ' +
          'same locales, or change this generator to emit per-application rules.',
      );
    }
  }

  return expected;
}

const HASHED_EXTENSIONS = ['js', 'css', 'woff2', 'svg', 'png', 'webp', 'ico'];
const UNHASHED_SCRIPTS = ['ngsw-worker.js', 'safety-worker.js'];

function render(apps, locales) {
  const appsAlternation = apps.join('|');
  const localesAlternation = locales.join('|');
  const extensionList = HASHED_EXTENSIONS.map((extension) => `*.${extension}`).join(' ');
  const workerList = UNHASHED_SCRIPTS.map((script) => `*/${script}`).join(' ');

  return `# GENERATED by scripts/gen-ui-config.mjs — do not edit, do not commit.
# apps=(${appsAlternation}) locales=(${localesAlternation}) default-locale=${DEFAULT_LOCALE_SEGMENT} root-app=${ROOT_APP}
#
# This is the browser-client container's own file server, NOT the public router. The public router
# lives in the bike-rental repository and forwards to here everything it does not publish itself.
#
# NO RULE IS WRITTEN PER APPLICATION OR PER LOCALE. The two alternations above are the only places
# either list appears, so adding a language or an application changes their contents and never the
# number of rules. '${DEFAULT_LOCALE_SEGMENT}' is named once more below, as the fallback target.
{
	admin off
	auto_https off
}

:${LISTEN_PORT} {
	# To stdout, so the host's log collector picks it up off the Docker socket like every other service
	# in the stack. Without it this container is the only publicly-reachable thing on the host that
	# cannot answer "who served that request" — including the refusals it now issues on the router's
	# behalf.
	log {
		output stdout
		format console
	}

	root * /srv
	encode zstd gzip

	# CACHING IS PARTITIONED, NOT LAYERED. The three matchers below are pairwise disjoint and together
	# cover every request, because Caddy does not promise that a later header directive overrides an
	# earlier one — relying on that silently leaves assets revalidating on every load.
	#
	# The partition is by extension rather than by a list of shell filenames on purpose: the shell is
	# normally requested as /app/locale/ and a deep link names no file at all, so a filename list is
	# exactly what leaves those two — the most common requests there are — uncovered.

	# Content-hashed filenames. Safe to pin forever.
	@immutable {
		path ${extensionList}
		not path ${workerList}
	}
	header @immutable Cache-Control "public, max-age=31536000, immutable"

	# The service worker scripts carry no content hash. Pinning one makes a bad release unreachable on
	# every client that cached it.
	@workers path ${workerList}
	header @workers Cache-Control "no-cache"

	# The shell, the manifests and every deep link.
	@volatile not path ${extensionList}
	header @volatile Cache-Control "no-cache"

	# route, not bare handle blocks: the order below is deliberate and must not be re-sorted by
	# specificity. Same reasoning as the public router's Caddyfile.
	route {
		# The one path that does not depend on which applications exist. The container healthcheck and
		# the production host's deploy script both probe it, and neither should have to be told the
		# application list to do so. It carries no detail on purpose: it is reachable from the internet,
		# because the public router forwards everything it does not publish itself to this container.
		handle /healthz {
			respond "ok" 200
		}

		# THE SITE ROOT. '${ROOT_APP}' is built with a base href of '/', so its locales ARE the top-level
		# URLs and there is no segment to redirect to — only a locale. Answered here rather than in the
		# public router because that router does not know which applications exist, and must not start to.
		redir / /${DEFAULT_LOCALE_SEGMENT}/ 302

		# A built locale. Serve the requested file when it exists, otherwise the shell of that same
		# locale — which is what makes a deep link such as /${apps[0]}/${DEFAULT_LOCALE_SEGMENT}/… work.
		@built path_regexp ui ^/(${appsAlternation})/(${localesAlternation})(/.*)?$
		handle @built {
			try_files {path} /{re.ui.1}/{re.ui.2}/index.html
			file_server
		}

		# A known application carrying no locale at all. Answered separately from the rule below so the
		# redirect lands on a directory WITH its trailing slash and the browser makes one hop, not two.
		@bare path_regexp bare ^/(${appsAlternation})/?$
		redir @bare /{re.bare.1}/${DEFAULT_LOCALE_SEGMENT}/ 302

		# A known application carrying a locale that was not built. The optional group swallows the
		# locale-shaped segment; the remainder of the path is preserved across the redirect.
		@fallback path_regexp fb ^/(${appsAlternation})(?:/[A-Za-z]{2}(?:-[A-Za-z0-9]+)?)?(/.*)?$
		redir @fallback /{re.fb.1}/${DEFAULT_LOCALE_SEGMENT}{re.fb.2} 302

		# THE ROOT APPLICATION, whose locales are top-level URLs. Its files live under /srv/${ROOT_APP}
		# so that the image keeps one layer per application, but they are ADDRESSED without that segment —
		# which is why this block overrides the root rather than reusing the rule above.
		@root path_regexp root ^/(${localesAlternation})(/.*)?$
		handle @root {
			root * /srv/${ROOT_APP}
			try_files {path} /{re.root.1}/index.html
			file_server
		}

		# A locale-shaped segment at the root that was not built, with nothing after it. Separate from the
		# rule below so the redirect lands on a directory WITH its trailing slash and the browser makes one
		# hop, not two.
		@root_bare path_regexp ^/[A-Za-z]{2}(?:-[A-Za-z0-9]+)?/?$
		redir @root_bare /${DEFAULT_LOCALE_SEGMENT}/ 302

		# The same, carrying a path. Only a locale-SHAPED segment is swallowed: a longer first segment
		# does not match, so an unknown path stays a 404 instead of being redirected into the index page.
		@root_fallback path_regexp rfb ^/[A-Za-z]{2}(?:-[A-Za-z0-9]+)?(/.*)$
		redir @root_fallback /${DEFAULT_LOCALE_SEGMENT}{re.rfb.1} 302

		handle {
			respond 404
		}
	}
}
`;
}

for (const app of [ROOT_APP, ...CONTAINER_APPS]) {
  if (!APP_SEGMENT_PATTERN.test(app)) {
    throw new Error(
      `'${app}' is not a valid application segment — see CONTAINER_APPS in scripts/apps.mjs.`,
    );
  }
}

if (CONTAINER_APPS.includes(ROOT_APP)) {
  console.error(
    `ROOT_APP is '${ROOT_APP}', which is also in CONTAINER_APPS. An application is served either at ` +
      'the site root or under a segment of its own, never both — listing it twice would emit two ' +
      'sets of rules for it.',
  );
  process.exit(1);
}

if (!existsSync(STAGING)) {
  console.error(`No ${STAGING}/ directory found — run the staging assembly step first.`);
  process.exit(1);
}

try {
  assertEveryAppIsCopiedIntoTheImage();
  const locales = resolveLocaleSegments();
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, render(CONTAINER_APPS, locales));
  console.log(
    `Wrote ${OUTPUT} — root app '${ROOT_APP}' at /, apps (${CONTAINER_APPS.join('|')}), ` +
      `locales (${locales.join('|')}), fallback '${DEFAULT_LOCALE_SEGMENT}'.`,
  );
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
